#!/usr/bin/env python3
"""Generate the import files and the annotated card list from the cube source.

Inputs:  cube/cube_list.txt (sections + card names), data/cube_cards.json,
         tools/tags.py
Outputs: cube/2026_cube.txt, cube/2026_cube_cubecobra.csv, CARDLIST.md
"""
import collections
import csv
import json
import os
import sys
import unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
from tags import TAGS  # noqa: E402

SET_FAMILY = {
    "ecl": "Lorwyn Eclipsed", "ecc": "Lorwyn Eclipsed",
    "tmt": "TMNT", "tmc": "TMNT",
    "sos": "Secrets of Strixhaven", "soc": "Secrets of Strixhaven",
    "msh": "Marvel Super Heroes", "msc": "Marvel Super Heroes",
    "hob": "The Hobbit", "hoc": "The Hobbit",
    "fra": "Reality Fracture", "frc": "Reality Fracture",
    "trk": "Star Trek", "trc": "Star Trek",
}



def norm(s):
    return unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode().lower().replace('"', "").replace("'", "")


def main():
    cards = json.load(open(os.path.join(ROOT, "data", "cube_cards.json")))
    by_name = {}
    for c in cards:
        by_name[norm(c["name"])] = c
        by_name[norm(c["name"].split(" // ")[0])] = c

    sections = collections.OrderedDict()
    current = None
    for line in open(os.path.join(ROOT, "cube", "cube_list.txt"), encoding="utf-8"):
        line = line.strip()
        if not line:
            continue
        if line.startswith("## "):
            current = line[3:]
            sections[current] = []
            continue
        card = by_name[norm(line)]
        sections[current].append((line, card))

    def tags_for(short_name, card):
        return TAGS.get(short_name) or TAGS.get(card["name"].split(" // ")[0]) or []

    # plain text list
    with open(os.path.join(ROOT, "cube", "2026_cube.txt"), "w", encoding="utf-8") as fh:
        for _, items in sections.items():
            for _, c in items:
                fh.write(c["name"] + "\n")

    # CubeCobra CSV (same columns as CubeCobra's own CSV export)
    with open(os.path.join(ROOT, "cube", "2026_cube_cubecobra.csv"), "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh, lineterminator="\n", quoting=csv.QUOTE_ALL)
        w.writerow(["name", "CMC", "Type", "Color", "Set", "Collector Number", "Rarity",
                    "Color Category", "status", "Finish", "board", "maybeboard", "image URL",
                    "image Back URL", "tags", "Notes", "MTGO ID", "Custom", "Voucher", "Artist"])
        for sec, items in sections.items():
            for short, c in items:
                colors = "".join(x for x in "WUBRG" if x in c["color_identity"])
                w.writerow([c["name"], int(c["cmc"]), c["type_line"], colors, c["set"],
                            c["collector_number"], c["rarity"], "",
                            "Not Owned", "Non-foil", "mainboard", "false", "", "",
                            ";".join(tags_for(short, c)), "", "", "false", "false", ""])

    # annotated card list
    out = ["# 2026 Cube — Full Card List", "",
           "Generated by `tools/build_outputs.py`. Tags show the archetype(s) each card is drafted "
           "for and its role. See [README.md](README.md) for the design notes.", ""]
    for sec, items in sections.items():
        out.append(f"## {sec} ({len(items)})")
        out.append("")
        out.append("| Card | Cost | Type | Set | Tags |")
        out.append("|---|---|---|---|---|")
        for short, c in sorted(items, key=lambda x: (x[1]["cmc"], x[1]["name"])):
            cost = (c["mana_cost"] or "").replace("{", "").replace("}", "")
            t = tags_for(short, c)
            url = c.get("scryfall_uri", "").split("?")[0]
            out.append(f"| [{c['name']}]({url}) | {cost} | {c['type_line']} | {c['set'].upper()} | {', '.join(t)} |")
        out.append("")
    open(os.path.join(ROOT, "CARDLIST.md"), "w", encoding="utf-8").write("\n".join(out))

    # stats
    total = sum(len(v) for v in sections.values())
    print("total", total)
    for sec, items in sections.items():
        print(f"  {sec}: {len(items)}")
    fam = collections.Counter(SET_FAMILY[c["set"]] for items in sections.values() for _, c in items)
    print("by set family:", fam.most_common())
    arche = collections.Counter(t for items in sections.values() for s, c in items for t in tags_for(s, c))
    print("tags:", sorted(arche.items(), key=lambda x: -x[1]))
    missing = [s for items in sections.values() for s, c in items
               if not tags_for(s, c) and sections and c["type_line"].find("Land") < 0]
    print("untagged non-lands:", missing)


if __name__ == "__main__":
    main()
